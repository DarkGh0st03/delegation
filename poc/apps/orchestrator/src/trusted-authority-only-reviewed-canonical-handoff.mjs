/**
 * R382.5 — one-shot, privileged, reviewed Planning -> canonical Executor
 * handoff in the ORIGINAL authority-only Review Host.
 *
 * This is an in-process owner capability. Never publish it through HTTP,
 * OIDC, A2A, MCP, a Gemini FunctionTool or a workflow input.
 * An independently verified Engineer receipt is checked here for stable
 * session/revision/plan binding, and the ORIGINAL host independently checks
 * the actual signed grant again before issuing a Root.
 *
 * No model call, credential, approval or provider effect at construction.
 * The owner-provisioned callbacks remain private. A failed or ambiguous
 * operational transition retires the ORIGINAL Review Host; it never falls
 * back to the legacy Signed DAG, creates another signer or retries a Root.
 */
import {isIssuedDisposableOwnerSourceGate}
 from "./disposable-gemini-owner-source-gate-brand.mjs";
const SHA=/^[a-f0-9]{40}$/u;
const DIGEST=/^[a-f0-9]{64}$/u;
const ROOT_KEYS=["credential_id","valid_from","validity_seconds",
 "credential_status"];
const DEPS=["operationalSessionStore","gatewayTaskJournal",
 "issuerChildJournal","gatewayChildJournal","nativeCryptoPort",
 "effectFenceJournal","sequentialEffectJournal","completionObserver"];
const WORKFLOW_KEYS=["sdk","adaptive","createBranch","draftPullRequest"];
const proofStatus="signed_human_review_verified_only_not_oidc_admitted";
function deny(detail){
 throw Error("Canonical reviewed owner handoff denied: "+detail);
}
function object(x){return x!==null&&typeof x==="object"&&!Array.isArray(x);}
function exact(x,keys){return object(x)&&
 Object.keys(x).length===keys.length&&
 keys.every(k=>Object.hasOwn(x,k));}
function allowed(x,keys){return object(x)&&
 Object.keys(x).every(k=>keys.includes(k));}
function liveNative(){
 return process.env.DELEGATION_GATEWAY_ARCHITECTURE==="authority-only"&&
  process.env.APPROVED_RUNNER_NATIVE_MCP==="1";
}
function validatedProof(proof,sessionId,baseRevision,planDigest,engineerDid){
 return object(proof)&&
  proof.status===proofStatus&&
  proof.session_id===sessionId&&
  proof.base_revision===baseRevision&&
  proof.plan_digest===planDigest&&
  proof.authenticated_engineer_did===engineerDid&&
  proof.operational_root_issued===false&&
  proof.dag_executed===false;
}
function validatedProvision(result){
 const required=["root","dependencies","workflow","prepareNativeEffects"];
 if(!allowed(result,[...required,"installNativeAuthorization","startLocalWorkers",
   "ownerSourceGate"])||
     (Object.hasOwn(result,"ownerSourceGate")&&
      !isIssuedDisposableOwnerSourceGate(result.ownerSourceGate))||
    !required.every(key=>Object.hasOwn(result,key))||
    ["installNativeAuthorization","startLocalWorkers"].some(key=>
     Object.hasOwn(result,key)&&typeof result[key]!=="function")||
    typeof result.prepareNativeEffects!=="function"||
    !exact(result.root,ROOT_KEYS)||
    typeof result.root.credential_id!=="string"||
    result.root.credential_id.length<1||
    result.root.credential_id.length>256||
    !Number.isSafeInteger(result.root.validity_seconds)||
    result.root.validity_seconds<1||
    !Number.isFinite(Date.parse(result.root.valid_from))||
    !object(result.root.credential_status)||
    !allowed(result.dependencies,DEPS)||
    DEPS.some(k=>!Object.hasOwn(result.dependencies,k))||
    typeof result.dependencies.nativeCryptoPort?.issueChildViaPrivateMcp!=="function"||
    !allowed(result.workflow,WORKFLOW_KEYS)||
    (result.startLocalWorkers?Object.hasOwn(result.workflow,"sdk"):!object(result.workflow.sdk))||
    !object(result.workflow.adaptive)||
    !object(result.workflow.createBranch)||
    typeof result.workflow.createBranch.prepare!=="function"||
    typeof result.workflow.createBranch.execute!=="function")
  deny("original live Root, MCP native owner and Branch required");
 return result;
}

/**
 * readSignedReview MUST be the independent, owner-bound Ed25519 review
 * verifier for the SAME original Planning checkpoint. Only the ORIGINAL
 * Review Host can activate the Root and independently recheck its approval.
 *
 * provision is created by the trusted operator, not generated by the model.
 * It receives no signed VP, credentials or permission-grant overrides.
 */
export function createTrustedAuthorityOnlyReviewedCanonicalHandoff({
 reviewHost,readSignedReview,provision,
 sessionId,baseRevision,planDigest,engineerDid
}={}){
 if(!liveNative()||!SHA.test(baseRevision??"")||
    !DIGEST.test(planDigest??"")||
    typeof sessionId!=="string"||!sessionId.trim()||
    typeof engineerDid!=="string"||!engineerDid.startsWith("did:")||
    reviewHost?.readOnlySessionId!==sessionId||
    reviewHost?.phase!=="planning"||
    typeof reviewHost?.activateOperational!=="function"||
    typeof reviewHost?.admitOperationalExecution!=="function"||
    typeof reviewHost?.close!=="function"||
    typeof readSignedReview!=="function"||
    typeof provision!=="function")
  deny("original Planning host, signed review pins and native owner required");
 let closed=false,preparing=false,attempted=false;
 let flight,shutdown,retirementFlight;
 const retireOriginal=()=>{
  if(!retirementFlight)retirementFlight=Promise.resolve().then(
   ()=>reviewHost.close());
  return retirementFlight;
 };
 const review=async()=>{
  if(closed||preparing||attempted||!liveNative()||
     reviewHost.phase!=="planning")
   deny("signed original review unavailable");
  const receipt=await readSignedReview();
  if(!validatedProof(receipt,sessionId,baseRevision,planDigest,engineerDid))
   deny("Engineer-signed immutable Planning review mismatched");
  if(closed||reviewHost.phase!=="planning"||!liveNative())
   deny("original review retired during signature check");
  return Object.freeze({
   status:proofStatus,session_id:sessionId,
   base_revision:baseRevision,plan_digest:planDigest,
   authenticated_engineer_did:engineerDid,
   operational_root_issued:false,dag_executed:false
  });
 };
 const close=()=>{
  if(shutdown)return shutdown;
  closed=true; // fence all future owner operations synchronously
  shutdown=(async()=>{
   let error;
   try{await retireOriginal();}catch(e){error=e;}
   if(flight)try{await flight;}catch{/* caller receives own failure */}
   if(error)deny("original Root retirement unconfirmed");
  })();
  return shutdown;
 };
 return Object.freeze({
  async reviewReadiness(){return review();},
  runApprovedCanonical(){
   if(closed||preparing||attempted||!liveNative()||
      reviewHost.phase!=="planning")
    deny("one-use original canonical execution already attempted");
   preparing=true; // serialize BEFORE first asynchronous review load
   const running=(async()=>{
    try{
     const signed=await readSignedReview();
     if(!validatedProof(signed,sessionId,baseRevision,planDigest,engineerDid))
      deny("Engineer-signed immutable Planning review mismatched");
     if(closed||reviewHost.phase!=="planning"||!liveNative())
      deny("original signed review changed before activation");
     attempted=true; // no retry after private provisioning can begin
     const owned=validatedProvision(await provision());
     if(closed||reviewHost.phase!=="planning"||!liveNative())
      deny("original owner retired before Root");
     // The Review Host re-reads and independently verifies the signed
     // approved permission subset before its durable issue intent.
     await reviewHost.activateOperational(owned.root);
     if(closed||reviewHost.phase!=="operational"||!liveNative())
      deny("original Root retired after activation");
     const execution=await reviewHost.admitOperationalExecution({
      ...owned.dependencies,privateChildMcpTransport:"native-stdio"
     });
     if(closed||reviewHost.phase!=="operational"||!liveNative())
      deny("original Executor retired after native MCP admission");
     if(!execution?.gateway||
        typeof execution.bindNativeGatewayEffects!=="function"||
        typeof execution.runCanonicalOperationalWorkflow!=="function")
      deny("original Review Host canonical launcher unavailable");
     // The native ports must be built for the newly admitted Gateway.
     // The original Host verifies their identity before any Branch effect.
     const effects=await owned.prepareNativeEffects(execution.gateway);
     if(closed||reviewHost.phase!=="operational"||!liveNative())
      deny("original Executor retired before native effect binding");
     execution.bindNativeGatewayEffects(
      owned.ownerSourceGate?{...effects,
       ownerSourceGate:owned.ownerSourceGate}:effects);
     await owned.installNativeAuthorization?.();
     if(closed||reviewHost.phase!=="operational"||!liveNative())
      deny("original Executor retired before canonical execution");
     let workers,result;
     try{
      workers=await owned.startLocalWorkers?.();
      if(closed||reviewHost.phase!=="operational"||!liveNative())
       deny("original Executor retired during local worker startup");
      result=await execution.runCanonicalOperationalWorkflow(workers?
       {...owned.workflow,sdk:workers.sdk}:owned.workflow);
     }finally{
      await workers?.close();
     }
     if(closed)deny("original Review Host retired during execution");
     return result;
    }catch(e){
     if(attempted){
      // A Rust issue, Task, or Gateway effect MAY have happened.
      // Mark closed synchronously. Do NOT call close() here: it waits
      // for this in-flight promise and would deadlock on itself.
      closed=true;
      try{await retireOriginal();}catch{
       deny("original Root retirement unconfirmed after ambiguous execution");
      }
     }
     throw e;
    }finally{
     preparing=false;
    }
   })();
   flight=running;
   void running.finally(()=>{if(flight===running)flight=undefined;})
    .catch(()=>{});
   return running;
  },
  close,
  get status(){return closed?"closing_or_closed":
   attempted?"canonical_execution_selected":
   preparing?"signed_review_in_progress":"awaiting_human_review";}
 });
}
