type FetchLike = typeof fetch;

export const SPECIALIZED_TOOL_NAMES = [
  "read_file",
  "update_file",
  "create_file",
  "run_tests"
] as const;
export type SpecializedToolName = (typeof SPECIALIZED_TOOL_NAMES)[number];

/** Owner-private port; implementations must resolve request IDs in the
 * owner's shared store and enforce prebound Task/operation/HEAD pins. */
export interface TrustedEffectStagingPort {
  stage(requestId:string):Promise<unknown>;
  /** Optional exact read-only effect pin from the authenticated Task registry. */
  stagedTool?:"read_file"|"update_file"|"create_file"|"run_tests"|"read_then_update"|"read_then_create"|
    "read_then_write_set";
  /** Owner-only independent native evidence confirmation, never model data. */
  attest?(requestId:string,tool:"read_file"|"update_file"|"create_file"):Promise<void>;
  reportNoChange?(requestId:string):Promise<void>;
  /** Test-source rule of the project profile, from the owner Task registry. */
  readonly projectTestSourceProfile?:unknown;
  /** read_then_update/read_then_create: signed reads before the single write,
   * as fixed by the owner's durable effect manifest (never model data). */
  readonly plannedReads?:number;
  /** Phase W: owner staging of the Gateway write batch (ID only) and the
   * owner attestation of its per-file evidence after the single HEAD-CAS. */
  stageWriteSet?(batchId:string):Promise<unknown>;
  attestWriteSet?(batchId:string):Promise<void>;
}

export interface GatewayControlledToolClientConfig {
  /** Installed only by the trusted host, never from tool/A2A arguments. */
  trustedEffectStager?:TrustedEffectStagingPort;
  gatewayBaseUrl: string;
  agentRole: SpecializedAgentRole;
  taskId: string;
  evidenceHandler: DelegationEvidenceHandler;
  /** Opt-in trusted crypto MCP path, never exposed as a model tool. */
  cryptoPresentation?: CryptoPresentationPort;
  timeoutMs?: number;
  /** Long execute timeout only for the controlled run_tests tool. */
  runnerExecuteTimeoutMs?: number;
  fetchFn?: FetchLike;
  signal?: AbortSignal;
  /** Exact signed Task read grants, never model arguments. */
  approvedDiagnosticReadPaths?:readonly string[];
  /** Exact signed update_file grants, never generated by the model. */
  approvedDiagnosticWritePaths?:readonly string[];
}

function errorMessage(body: unknown, fallback: string): string {
  if (
    typeof body === "object" &&
    body !== null &&
    "message" in body &&
    typeof (body as { message?: unknown }).message === "string"
  ) {
    return (body as { message: string }).message;
  }
  if (
    typeof body === "object" &&
    body !== null &&
    "error" in body &&
    typeof (body as { error?: unknown }).error === "string"
  ) {
    return (body as { error: string }).error;
  }
  return fallback;
}

async function parseJson(response: Response, label: string): Promise<unknown> {
  const raw = await response.text();
  if (raw.length === 0) return {};
  try {
    return JSON.parse(raw);
  } catch {
    throw new ControlledToolError(
      "tool_unavailable",
      `${label} returned invalid JSON`,
      { statusCode: response.status }
    );
  }
}

export class GatewayControlledToolClient {
  readonly #trustedEffectStager?:TrustedEffectStagingPort;
  readonly #gatewayBaseUrl: string;
  readonly #agentRole: SpecializedAgentRole;
  readonly #taskId: string;
  readonly #evidenceHandler: DelegationEvidenceHandler;
  readonly #cryptoPresentation?: CryptoPresentationPort;
  readonly #timeoutMs: number;
  readonly #runnerExecuteTimeoutMs: number;
  readonly #fetch: FetchLike;
  readonly #signal?: AbortSignal;
  readonly #approvedDiagnosticReadPaths:readonly string[];
  readonly #approvedDiagnosticWritePaths:readonly string[];
  /** SHA-256 of each file content read (and attested) in this Task. */
  readonly #readContentSha256=new Map<string,string>();

  constructor(config: GatewayControlledToolClientConfig) {
    if (config.gatewayBaseUrl.trim().length === 0) {
      throw new Error("Gateway base URL cannot be empty");
    }
    if (config.taskId.trim().length === 0) {
      throw new Error("Gateway task id cannot be empty");
    }

    if(config.trustedEffectStager!==undefined&&
       typeof config.trustedEffectStager?.stage!=="function")
      throw new Error("Invalid trusted effect staging port");
    this.#trustedEffectStager=config.trustedEffectStager;
    this.#gatewayBaseUrl = config.gatewayBaseUrl.replace(/\/+$/u, "");
    this.#agentRole = config.agentRole;
    this.#taskId = config.taskId;
    this.#evidenceHandler = config.evidenceHandler;
    this.#cryptoPresentation = config.cryptoPresentation;
    this.#timeoutMs = config.timeoutMs ?? 10_000;
    this.#runnerExecuteTimeoutMs = config.runnerExecuteTimeoutMs ?? this.#timeoutMs;
    if(!Number.isSafeInteger(this.#runnerExecuteTimeoutMs) ||
       this.#runnerExecuteTimeoutMs<1 || this.#runnerExecuteTimeoutMs>960_000){
      throw new Error("Controlled Runner timeout must be between 1 and 960000 ms");
    }
    this.#fetch = config.fetchFn ?? fetch;
    this.#signal = config.signal;
    this.#approvedDiagnosticReadPaths=[...(config.approvedDiagnosticReadPaths??[])];
    this.#approvedDiagnosticWritePaths=[...(config.approvedDiagnosticWritePaths??[])];
  }

  async invoke(
    tool: SpecializedToolName,
    args: Record<string, unknown>
  ): Promise<unknown> {
    this.#signal?.throwIfAborted();
    // A "change" identical to the file just read is not a change: answer
    // locally, BEFORE Gateway Prepare, so the single write grant stays
    // unused and the owner can record a verified no-change outcome.
    if(tool==="update_file"&&this.#trustedEffectStager?.stagedTool==="read_then_update"&&
       typeof args.path==="string"&&typeof args.content==="string"&&
       this.#readContentSha256.get(args.path)===
        createHash("sha256").update(args.content,"utf8").digest("hex"))
      throw new ControlledToolError("no_change",
        "The new content is identical to the file read in this Task, so no change is needed. "+
        "Do not call update_file again with the same content; reply with a short report explaining "+
        "why the file already satisfies the instruction.");
    // A model can request CREATE only through a privately prebound
    // single-effect Task/Child selected by the HMAC owner registry. The same
    // native one-shot MCP presentation used by the original A2A Task must
    // be installed before Prepare. No unsigned/legacy presenter fallback.
    const ownerCreate=this.#trustedEffectStager?.stagedTool==="create_file";
    // Reads of the signed context files, then ONE create of a new file.
    const mixedCreate=this.#trustedEffectStager?.stagedTool==="read_then_create";
    // Test CREATE is not an application-source capability. It needs
    // the original native single-effect stager AND an exact test source,
    // independently bound to the signed Task by Gateway/Rust/OPA.
    const nativeCreateRoleAllowed=APPLICATION_ROLES.includes(this.#agentRole)||
      (this.#agentRole==="test"&&isProjectTestSource(args.path,
        this.#trustedEffectStager?.projectTestSourceProfile));
    // Phase W: a write-set Task writes ONLY through write_files (one batch).
    if(this.#trustedEffectStager?.stagedTool==="read_then_write_set"&&tool!=="read_file")
      throw new ControlledToolError("authorization_denied",
        "A write-set Task writes all its signed files with write_files, in one batch");
    if(this.#trustedEffectStager?.stagedTool==="read_then_update"&&
       tool!=="read_file"&&tool!=="update_file")
      throw new ControlledToolError("authorization_denied",
        "Mixed native Task supports only exact read_file and update_file");
    if(mixedCreate&&tool!=="read_file"&&tool!=="create_file")
      throw new ControlledToolError("authorization_denied",
        "Mixed native Task supports only exact read_file and create_file");
    if(ownerCreate&&tool!=="create_file")
      throw new ControlledToolError("authorization_denied",
        "Signed CREATE Task cannot invoke a different repository operation");
    if(tool==="create_file"&&
       (process.env.DELEGATION_GATEWAY_ARCHITECTURE==="authority-only"||
        this.#trustedEffectStager!==undefined)&&
       (!(ownerCreate||mixedCreate)||
        !nativeCreateRoleAllowed||
        !this.#cryptoPresentation||
        process.env.DELEGATION_GATEWAY_ARCHITECTURE!=="authority-only"||
        process.env.APPROVED_RUNNER_NATIVE_MCP!=="1"))
      throw new ControlledToolError("authorization_denied",
        "Authority-only CREATE requires original native Child/Task and private MCP");
    let prepareResponse: Response;
    try {
      prepareResponse = await this.#fetch(
        `${this.#gatewayBaseUrl}/v1/authorization/prepare`,
        {
          method: "POST",
          headers: { "content-type": "application/json" },
          body: JSON.stringify({
            task_id: this.#taskId,
            agent_role: this.#agentRole,
            tool,
            arguments: args
          }),
          signal: this.#signal
            ? AbortSignal.any([this.#signal, AbortSignal.timeout(this.#timeoutMs)])
            : AbortSignal.timeout(this.#timeoutMs)
        }
      );
    } catch (error) {
      throw new ControlledToolError(
        "tool_unavailable",
        `Gateway prepare is unavailable: ${error instanceof Error ? error.message : String(error)}`,
        {reason:"upstream_unavailable"}
      );
    }

    const preparedBody = await parseJson(prepareResponse, "Gateway prepare");
    if (!prepareResponse.ok) {
      throw new ControlledToolError(
        prepareResponse.status >= 500 ? "tool_unavailable" : "invalid_tool_call",
        errorMessage(
          preparedBody,
          `Gateway prepare failed with HTTP ${prepareResponse.status}`
        ),
        {
          statusCode: prepareResponse.status,
          reason: prepareResponse.status >= 500 ? "upstream_unavailable" :
            safeToolFailureReason((preparedBody as {prepare_reason?:unknown})?.prepare_reason)??"gateway_prepare_rejected"
        }
      );
    }

    const prepared = preparedBody as PreparedGatewayAuthorization;
    if (
      typeof prepared.request_id !== "string" ||
      typeof prepared.audience !== "string" ||
      typeof prepared.challenge !== "string" ||
      typeof prepared.expires_at !== "string" ||
      typeof prepared.required_permission !== "object" ||
      prepared.required_permission === null
    ) {
      throw new ControlledToolError(
        "tool_unavailable",
        "Gateway prepare returned a malformed authorization challenge"
      );
    }

    this.#signal?.throwIfAborted();
    // The authenticated owner may additionally select one read-only
    // flight. Legacy mutation/Runner ports keep their previous behavior.
    // A read in an update Task is NOT silently converted into a second flight.
    const mixed=this.#trustedEffectStager?.stagedTool==="read_then_update";
    const writeSetTask=this.#trustedEffectStager?.stagedTool==="read_then_write_set";
    const ownerRead=tool==="read_file"&&
      (this.#trustedEffectStager?.stagedTool==="read_file"||mixed||mixedCreate||writeSetTask);
    const ownerWrite=(tool==="update_file"||tool==="run_tests")&&
      (this.#trustedEffectStager?.stagedTool===undefined||
       this.#trustedEffectStager?.stagedTool===tool||
       (mixed&&tool==="update_file"));
    const ownerNativeCreate=tool==="create_file"&&(ownerCreate||mixedCreate);
    if(this.#trustedEffectStager&&(ownerRead||ownerWrite||ownerNativeCreate)){
      try{
        await this.#trustedEffectStager.stage(prepared.request_id);
      }catch{
        // Owner errors may contain private provider data. Fail closed before
        // presentation/execute without exposing the error to model tools.
        throw new ControlledToolError("tool_unavailable",
          "Trusted effect staging failed");
      }
      this.#signal?.throwIfAborted();
    }
    // Both paths keep the signed VP in trusted runtime memory; the MCP path
    // returns only an opaque reference to its private worker before executing.
    const signedVp = this.#cryptoPresentation
      ? await this.#cryptoPresentation.createSignedPresentation(prepared)
      : await this.#evidenceHandler.createPresentation(prepared);
    this.#signal?.throwIfAborted();

    let executeResponse: Response;
    try {
      executeResponse = await this.#fetch(
        `${this.#gatewayBaseUrl}/v1/authorization/execute`,
        {
          method: "POST",
          headers: { "content-type": "application/json" },
          body: JSON.stringify({
            request_id: prepared.request_id,
            signed_vp: signedVp
          }),
          signal: this.#signal
            ? AbortSignal.any([this.#signal, AbortSignal.timeout(
                tool==="run_tests" ? this.#runnerExecuteTimeoutMs : this.#timeoutMs)])
            : AbortSignal.timeout(
                tool==="run_tests" ? this.#runnerExecuteTimeoutMs : this.#timeoutMs)
        }
      );
    } catch (error) {
      throw new ControlledToolError(
        "tool_unavailable",
        `Gateway execute is unavailable: ${error instanceof Error ? error.message : String(error)}`
      );
    }

    this.#signal?.throwIfAborted();
    const executeBody = await parseJson(executeResponse, "Gateway execute");
    if (!executeResponse.ok) {
      throw new ControlledToolError(
        executeResponse.status >= 500 ? "tool_unavailable" : "authorization_denied",
        errorMessage(
          executeBody,
          `Gateway execute failed with HTTP ${executeResponse.status}`
        ),
        {
          statusCode: executeResponse.status,
          // Only fixed Gateway error codes cross the model-facing boundary.
          // The human-readable provider/Gateway message is never used as evidence.
          reason: executeResponse.status >= 500 ? "upstream_unavailable" :
            safeToolFailureReason((executeBody as {error?:unknown})?.error) ??
            "gateway_execute_unclassified"
        }
      );
    }

    // In owner-staged execution, a 200 from an intermediate proxy is not
    // evidence that the exact one-shot request was authorized. Every effect
    // (and any read on this owner client) must match the Gateway's original
    // request_id AND explicit allow decision. No retry follows a mismatch.
    if(this.#trustedEffectStager){
      const bound=executeBody!==null&&typeof executeBody==="object"
        ? executeBody as {request_id?:unknown;decision?:unknown}
        : null;
      if(bound?.request_id!==prepared.request_id||
         bound?.decision!=="allow")
        throw new ControlledToolError("authorization_denied",
          "Authority-only Gateway execute response lacks exact request decision",
          {reason:"gateway_execute_unclassified"});
    }
    if (
      typeof executeBody !== "object" ||
      executeBody === null ||
      !("execution" in executeBody)
    ) {
      throw new ControlledToolError(
        "tool_unavailable",
        "Gateway execute response is missing execution result"
      );
    }

    const execution = (executeBody as { execution: unknown }).execution;
    if(ownerNativeCreate){
      const created=execution!==null&&typeof execution==="object"&&
        !Array.isArray(execution)?execution as Record<string,unknown>:null;
      if(!created||
         Object.keys(created).sort().join(",")!==
          "blob_sha,branch,commit_sha,path,performed,provider,revision,tool"||
         created.provider!=="gitea"||
         created.performed!==true||created.tool!=="create_file"||
         created.branch!==args.branch||created.path!==args.path||
         typeof args.content!=="string"||
         typeof created.commit_sha!=="string"||
         !/^[a-f0-9]{40}$/u.test(created.commit_sha)||
         created.revision!==created.commit_sha||
         typeof created.blob_sha!=="string"||
         !/^[a-f0-9]{40}$/u.test(created.blob_sha)){
        throw new ControlledToolError("authorization_denied",
          "Native CREATE has no exact Gateway CAS result",
          {reason:"gateway_execute_unclassified"});
      }
      // A structurally matching provider result is NOT an A2A completion
      // receipt: the original owner subsequently attests the private MAC,
      // pinned old-file absence and Task flight independently.
    }
    if (
      tool === "run_tests" &&
      typeof execution === "object" &&
      execution !== null &&
      "status" in execution &&
      (execution as { status?: unknown }).status === "fail"
    ) {
      throw new ControlledToolError(
        "tests_failed",
        "Controlled Test Runner reported a failing test outcome",
        { details: safeRunnerFailureDetails(execution,
          this.#approvedDiagnosticReadPaths,this.#approvedDiagnosticWritePaths) }
      );
    }

    // A model/HTTP claim cannot advance a mixed Task. Check the
    // exact native Gitea result, then ask the authenticated owner to
    // INDEPENDENTLY inspect the original provider receipt and seal it.
    // If this fails, the one-use owner slot remains terminally consumed.
    if(mixed||mixedCreate){
      const observed=execution!==null&&typeof execution==="object"
        ? execution as Record<string,unknown>:null;
      const revision=tool==="read_file"?observed?.revision:observed?.commit_sha;
      if(!observed||observed.provider!=="gitea"||
         observed.performed!==true||observed.tool!==tool||
         observed.branch!==args.branch||observed.path!==args.path||
         typeof revision!=="string"||!/^[a-f0-9]{40}$/u.test(revision)||
         typeof this.#trustedEffectStager?.attest!=="function")
        throw new ControlledToolError("authorization_denied",
          "Mixed native effect lacks exact Gitea execution receipt");
      try{
        await this.#trustedEffectStager.attest(prepared.request_id,tool as
          "read_file"|"update_file"|"create_file");
      }catch{
        throw new ControlledToolError("tool_unavailable",
          "Trusted independent effect attestation failed");
      }
      this.#signal?.throwIfAborted();
    }
    if(ownerNativeCreate){
      // Never relay unrecognized Gateway/provider metadata or auth material
      // to a model even after the private Task and exact CAS shape checks.
      const result=execution as Record<string,unknown>;
      return Object.freeze({
       provider:"gitea",performed:true,tool:"create_file",
       branch:result.branch,path:result.path,
       revision:result.revision,commit_sha:result.commit_sha,
       blob_sha:result.blob_sha
      });
    }
    if(tool==="read_file"&&(this.#trustedEffectStager?.stagedTool==="read_then_update"||
        this.#trustedEffectStager?.stagedTool==="read_then_write_set")&&
       typeof args.path==="string"&&execution&&typeof execution==="object"&&
       typeof (execution as {content?:unknown}).content==="string")
      this.#readContentSha256.set(args.path,createHash("sha256")
        .update((execution as {content:string}).content,"utf8").digest("hex"));
    return execution;
  }

  /** Phase R: batch reads are possible only in an owner-staged reads+write Task. */
  get supportsBatchReads():boolean{
    const staged=this.#trustedEffectStager?.stagedTool;
    return staged==="read_then_update"||staged==="read_then_create"||staged==="read_then_write_set";
  }

  /** Phase W: batch writes are possible only in an owner-staged write-set Task. */
  get supportsBatchWrites():boolean{
    const p=this.#trustedEffectStager;
    return p?.stagedTool==="read_then_write_set"&&typeof p.stageWriteSet==="function"&&
      typeof p.attestWriteSet==="function";
  }

  /**
   * Phase W: write ALL the signed files of this write-set Task with ONE VP.
   * One Gateway write-batch Prepare (N ordinary update/create records with
   * one challenge), owner staging of the write-set (owner preflight + durable
   * flight), ONE wallet presentation disclosing the N Gateway-derived
   * permissions, then the N Executes in the canonical order returned by the
   * Gateway: the first N-1 are only validated, the last publishes the whole
   * set with one commit and one HEAD-CAS. Finally the owner attests every
   * per-file evidence. Contents come from the model; paths and operations
   * must be exactly the signed writes (checked by the Gateway and owner).
   */
  async writeFiles(branch:string,changes:readonly {path:string;operation:"update_file"|"create_file";
    content:string}[]):Promise<{commit_sha:string;files:{path:string;operation:string}[]}>{
    this.#signal?.throwIfAborted();
    const port=this.#trustedEffectStager;
    if(!this.supportsBatchWrites||!port?.stageWriteSet||!port.attestWriteSet)
      throw new ControlledToolError("authorization_denied",
        "Batch writes require an owner-staged signed write-set Task");
    if(!Array.isArray(changes)||changes.length<2||changes.length>8||
       new Set(changes.map(c=>c?.path)).size!==changes.length||
       changes.some(c=>!c||typeof c.path!=="string"||typeof c.content!=="string"||
        (c.operation!=="update_file"&&c.operation!=="create_file")))
      throw new ControlledToolError("invalid_tool_call",
        "write_files needs 2-8 distinct {path, operation, content} changes");
    for(const c of changes)
      if(c.operation==="update_file"&&this.#readContentSha256.get(c.path)===
         createHash("sha256").update(c.content,"utf8").digest("hex"))
        throw new ControlledToolError("invalid_tool_call",
          `The new content of ${c.path} is identical to the file read: every signed file must change`);
    const timeout=()=>this.#signal
      ?AbortSignal.any([this.#signal,AbortSignal.timeout(this.#timeoutMs)])
      :AbortSignal.timeout(this.#timeoutMs);
    let prepareResponse:Response;
    try{
      prepareResponse=await this.#fetch(`${this.#gatewayBaseUrl}/v1/authorization/prepare-write-batch`,{
        method:"POST",headers:{"content-type":"application/json"},
        body:JSON.stringify({task_id:this.#taskId,agent_role:this.#agentRole,tool:"write_files",
          arguments:{branch,changes:changes.map(c=>({path:c.path,operation:c.operation,content:c.content}))}}),
        signal:timeout()});
    }catch(error){
      throw new ControlledToolError("tool_unavailable",
        `Gateway write batch prepare is unavailable: ${error instanceof Error?error.message:String(error)}`,
        {reason:"upstream_unavailable"});
    }
    const body=await parseJson(prepareResponse,"Gateway write batch prepare");
    if(!prepareResponse.ok)
      throw new ControlledToolError(prepareResponse.status>=500?"tool_unavailable":"invalid_tool_call",
        errorMessage(body,`Gateway write batch prepare failed with HTTP ${prepareResponse.status}`),
        {statusCode:prepareResponse.status,
         reason:prepareResponse.status>=500?"upstream_unavailable":"gateway_prepare_rejected"});
    const batch=body as {batch_id?:unknown;audience?:unknown;challenge?:unknown;expires_at?:unknown;items?:unknown};
    const items=Array.isArray(batch.items)?batch.items as
      {request_id?:unknown;path?:unknown;operation?:unknown;required_permission?:unknown}[]:[];
    const byPath=new Map(changes.map(c=>[c.path,c]));
    if(typeof batch.batch_id!=="string"||typeof batch.audience!=="string"||
       typeof batch.challenge!=="string"||typeof batch.expires_at!=="string"||
       items.length!==changes.length||
       new Set(items.map(i=>i?.path)).size!==items.length||
       items.some(i=>typeof i?.request_id!=="string"||typeof i.path!=="string"||
        byPath.get(i.path)?.operation!==i.operation||
        !i.required_permission||typeof i.required_permission!=="object"))
      throw new ControlledToolError("tool_unavailable","Gateway write batch prepare returned a malformed challenge");
    try{await port.stageWriteSet(batch.batch_id);}
    catch{throw new ControlledToolError("tool_unavailable","Trusted write-set staging failed");}
    this.#signal?.throwIfAborted();
    const permissions=items.map(i=>i.required_permission as PreparedGatewayAuthorization["required_permission"]);
    const prepared:PreparedGatewayAuthorization={request_id:batch.batch_id,audience:batch.audience,
      challenge:batch.challenge,required_permission:permissions[0]!,required_permissions:permissions,
      expires_at:batch.expires_at};
    // ONE presentation for the whole write-set.
    const signedVp=this.#cryptoPresentation
      ?await this.#cryptoPresentation.createSignedPresentation(prepared)
      :await this.#evidenceHandler.createPresentation(prepared);
    let published:Record<string,unknown>|undefined;
    for(const [index,item] of items.entries()){
      this.#signal?.throwIfAborted();
      let response:Response;
      try{
        response=await this.#fetch(`${this.#gatewayBaseUrl}/v1/authorization/execute`,{
          method:"POST",headers:{"content-type":"application/json"},
          body:JSON.stringify({request_id:item.request_id,signed_vp:signedVp}),signal:timeout()});
      }catch(error){
        throw new ControlledToolError("tool_unavailable",
          `Gateway execute is unavailable: ${error instanceof Error?error.message:String(error)}`);
      }
      const executeBody=await parseJson(response,"Gateway execute");
      if(!response.ok)
        throw new ControlledToolError(response.status>=500?"tool_unavailable":"authorization_denied",
          errorMessage(executeBody,`Gateway execute failed with HTTP ${response.status}`),
          {statusCode:response.status,reason:response.status>=500?"upstream_unavailable":
            safeToolFailureReason((executeBody as {error?:unknown})?.error)??"gateway_execute_unclassified"});
      const bound=executeBody!==null&&typeof executeBody==="object"
        ?executeBody as {request_id?:unknown;decision?:unknown;execution?:unknown}:null;
      const ex=bound?.execution!==null&&typeof bound?.execution==="object"
        ?bound.execution as Record<string,unknown>:null;
      const last=index===items.length-1;
      if(bound?.request_id!==item.request_id||bound?.decision!=="allow"||!ex||ex.provider!=="gitea"||
         (last?(ex.performed!==true||ex.tool!=="write_files"||ex.branch!==branch||
           typeof ex.commit_sha!=="string"||!/^[a-f0-9]{40}$/u.test(ex.commit_sha)):
          (ex.performed!==false||ex.write_set_item_validated!==true||ex.write_batch_id!==batch.batch_id)))
        throw new ControlledToolError("authorization_denied","Write batch lacks the exact Gateway execution receipt");
      if(last)published=ex;
    }
    const files=Array.isArray(published!.files)?published!.files as {path?:unknown;operation?:unknown}[]:[];
    if(files.length!==changes.length||files.some(f=>byPath.get(f.path as string)?.operation!==f.operation))
      throw new ControlledToolError("authorization_denied","Published write-set differs from the requested changes");
    try{await port.attestWriteSet(batch.batch_id);}
    catch{throw new ControlledToolError("tool_unavailable","Trusted independent write-set attestation failed");}
    return {commit_sha:published!.commit_sha as string,
      files:files.map(f=>({path:f.path as string,operation:f.operation as string}))};
  }

  /**
   * Phase R: read ALL the given signed files of this Task with ONE VP.
   * One Gateway batch Prepare (N ordinary role-bound read records sharing a
   * challenge), one wallet presentation disclosing the N Gateway-derived
   * permissions, then for each file, in order: owner staging -> Execute ->
   * exact Gitea receipt -> owner attestation (unchanged per-file evidence).
   * `paths` come from the trusted signed Task, never from the model.
   */
  async readFiles(branch:string,paths:readonly string[]):Promise<{files:unknown[]}>{
    this.#signal?.throwIfAborted();
    if(!this.supportsBatchReads||typeof this.#trustedEffectStager?.attest!=="function")
      throw new ControlledToolError("authorization_denied",
        "Batch reads require an owner-staged signed reads+write Task");
    if(!Array.isArray(paths)||paths.length<2||new Set(paths).size!==paths.length)
      throw new ControlledToolError("invalid_tool_call","A batch read needs distinct signed paths");
    const timeout=()=>this.#signal
      ?AbortSignal.any([this.#signal,AbortSignal.timeout(this.#timeoutMs)])
      :AbortSignal.timeout(this.#timeoutMs);
    let prepareResponse:Response;
    try{
      prepareResponse=await this.#fetch(`${this.#gatewayBaseUrl}/v1/authorization/prepare-read-batch`,{
        method:"POST",headers:{"content-type":"application/json"},
        body:JSON.stringify({task_id:this.#taskId,agent_role:this.#agentRole,
          tool:"read_files",arguments:{branch,paths:[...paths]}}),
        signal:timeout()
      });
    }catch(error){
      throw new ControlledToolError("tool_unavailable",
        `Gateway batch prepare is unavailable: ${error instanceof Error?error.message:String(error)}`,
        {reason:"upstream_unavailable"});
    }
    const body=await parseJson(prepareResponse,"Gateway batch prepare");
    if(!prepareResponse.ok)
      throw new ControlledToolError(prepareResponse.status>=500?"tool_unavailable":"invalid_tool_call",
        errorMessage(body,`Gateway batch prepare failed with HTTP ${prepareResponse.status}`),
        {statusCode:prepareResponse.status,
         reason:prepareResponse.status>=500?"upstream_unavailable":"gateway_prepare_rejected"});
    const batch=body as {batch_id?:unknown;audience?:unknown;challenge?:unknown;
      expires_at?:unknown;items?:unknown};
    const items=Array.isArray(batch.items)?batch.items as
      {request_id?:unknown;path?:unknown;required_permission?:unknown}[]:[];
    if(typeof batch.batch_id!=="string"||typeof batch.audience!=="string"||
       typeof batch.challenge!=="string"||typeof batch.expires_at!=="string"||
       items.length!==paths.length||
       items.some((item,i)=>typeof item?.request_id!=="string"||item.path!==paths[i]||
         !item.required_permission||typeof item.required_permission!=="object"))
      throw new ControlledToolError("tool_unavailable",
        "Gateway batch prepare returned a malformed authorization challenge");
    const permissions=items.map(item=>item.required_permission as
      PreparedGatewayAuthorization["required_permission"]);
    const prepared:PreparedGatewayAuthorization={
      request_id:batch.batch_id,audience:batch.audience,challenge:batch.challenge,
      required_permission:permissions[0]!,required_permissions:permissions,
      expires_at:batch.expires_at
    };
    this.#signal?.throwIfAborted();
    // ONE presentation for the whole batch (the wallet sees only the batch ID).
    const signedVp=this.#cryptoPresentation
      ?await this.#cryptoPresentation.createSignedPresentation(prepared)
      :await this.#evidenceHandler.createPresentation(prepared);
    const files:unknown[]=[];
    for(const [i,item] of items.entries()){
      const requestId=item.request_id as string;
      const path=paths[i]!;
      try{
        await this.#trustedEffectStager.stage(requestId);
      }catch{
        throw new ControlledToolError("tool_unavailable","Trusted effect staging failed");
      }
      this.#signal?.throwIfAborted();
      let executeResponse:Response;
      try{
        executeResponse=await this.#fetch(`${this.#gatewayBaseUrl}/v1/authorization/execute`,{
          method:"POST",headers:{"content-type":"application/json"},
          body:JSON.stringify({request_id:requestId,signed_vp:signedVp}),signal:timeout()
        });
      }catch(error){
        throw new ControlledToolError("tool_unavailable",
          `Gateway execute is unavailable: ${error instanceof Error?error.message:String(error)}`);
      }
      const executeBody=await parseJson(executeResponse,"Gateway execute");
      if(!executeResponse.ok)
        throw new ControlledToolError(executeResponse.status>=500?"tool_unavailable":"authorization_denied",
          errorMessage(executeBody,`Gateway execute failed with HTTP ${executeResponse.status}`),
          {statusCode:executeResponse.status,
           reason:executeResponse.status>=500?"upstream_unavailable":
             safeToolFailureReason((executeBody as {error?:unknown})?.error)??"gateway_execute_unclassified"});
      const bound=executeBody!==null&&typeof executeBody==="object"
        ?executeBody as {request_id?:unknown;decision?:unknown;execution?:unknown}:null;
      if(bound?.request_id!==requestId||bound?.decision!=="allow")
        throw new ControlledToolError("authorization_denied",
          "Authority-only Gateway execute response lacks exact request decision",
          {reason:"gateway_execute_unclassified"});
      const observed=bound.execution!==null&&typeof bound.execution==="object"
        ?bound.execution as Record<string,unknown>:null;
      if(!observed||observed.provider!=="gitea"||observed.performed!==true||
         observed.tool!=="read_file"||observed.branch!==branch||observed.path!==path||
         typeof observed.revision!=="string"||!/^[a-f0-9]{40}$/u.test(observed.revision))
        throw new ControlledToolError("authorization_denied",
          "Batch read lacks exact Gitea execution receipt");
      try{
        await this.#trustedEffectStager.attest(requestId,"read_file");
      }catch{
        throw new ControlledToolError("tool_unavailable","Trusted independent effect attestation failed");
      }
      if(typeof observed.content==="string")
        this.#readContentSha256.set(path,createHash("sha256").update(observed.content,"utf8").digest("hex"));
      files.push(observed);
      this.#signal?.throwIfAborted();
    }
    return {files};
  }
}
